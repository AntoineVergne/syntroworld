"""The Season 1 freeze (06 §8.1): docs 01 to 06 and the engine, hashed together.

``FREEZE.md`` lists the engine version and the sha256 of every frozen file. The test
``tests/test_freeze.py`` fails if a frozen file changes without a new manifest, so every
change after the freeze is a logged amendment (decisions.md, "Freeze").

    python -m synw.freeze            # check
    python -m synw.freeze --write    # rewrite FREEZE.md after a logged amendment
"""

import glob
import hashlib
import os
import sys

from . import __version__

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "FREEZE.md")
PATTERNS = ["source-docs/0[1-6]-*.md", "worlds/**/*.yaml", "schemas/*.json", "synw/**/*.py"]


def frozen_files():
    out = set()
    for pat in PATTERNS:
        out.update(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, pat), recursive=True))
    return sorted(p.replace(os.sep, "/") for p in out)


def digest(rel):
    with open(os.path.join(ROOT, rel), "rb") as fh:
        return hashlib.sha256(fh.read().replace(b"\r\n", b"\n")).hexdigest()


def current():
    return {p: digest(p) for p in frozen_files()}


def render(hashes):
    lines = ["# Season 1 freeze (06 §8.1)", "",
             "Docs 01 to 06 and the engine, frozen together after M0 to M3 passed. Generated by",
             "`python -m synw.freeze --write`; any change after this is an amendment logged in",
             "`decisions.md` (Freeze).", "",
             f"Engine version: `{__version__}`", "", "| File | sha256 |", "|---|---|"]
    lines += [f"| `{p}` | `{h}` |" for p, h in sorted(hashes.items())]
    return "\n".join(lines) + "\n"


def recorded():
    if not os.path.exists(MANIFEST):
        return None, {}
    version, hashes = None, {}
    for line in open(MANIFEST, encoding="utf-8"):
        if line.startswith("Engine version:"):
            version = line.split("`")[1]
        elif line.startswith("| `"):
            parts = line.split("`")
            hashes[parts[1]] = parts[3]
    return version, hashes


def diff():
    version, old = recorded()
    new = current()
    changed = sorted(p for p in set(old) | set(new) if old.get(p) != new.get(p))
    return version, changed


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--write" in argv:
        with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render(current()))
        print(f"wrote {MANIFEST}")
        return 0
    version, changed = diff()
    if version != __version__:
        print(f"engine version {__version__} differs from the frozen {version}")
    for p in changed:
        print(f"changed since the freeze: {p}")
    return 1 if changed or version != __version__ else 0


if __name__ == "__main__":
    sys.exit(main())
